//! What Quit Banda asks while Agents work, in one set of words everywhere
//! (ADR 0086, decision 3): `banda stop` in a terminal, and through the
//! contract (`sdk/contract/src/quit.ts`) the window's page, macOS's dialog
//! and the menu bar. Cancel is the default: a stray Quit leaves the
//! Agents working. With none at work, Quit asks nothing.

use serde::Serialize;

/// The title and the line under it, for one Agent and for more, where
/// `{n}` is how many and `{here}` this machine.
const ONE: Said = Said {
    title: "An Agent works on {here}",
    detail: "Quitting Banda stops it too.",
};
const MANY: Said = Said {
    title: "{n} Agents work on {here}",
    detail: "Quitting Banda stops them too.",
};

/// The button that quits anyway; the other, the default, is Cancel.
pub const QUIT: &str = "Quit anyway";

/// What Restart now says under Quit's title, for one Agent and for more,
/// and its button (ADR 0119, decision 3): the engine's restart onto a new
/// copy stops them as Quit does.
const RESTART_ONE: &str = "Restarting Banda's engine stops it too.";
const RESTART_MANY: &str = "Restarting Banda's engine stops them too.";
pub const RESTART: &str = "Restart anyway";

/// This machine, as the words name it: a Mac, or any other computer.
const MAC: &str = "this Mac";
const ELSEWHERE: &str = "this computer";

#[derive(Clone, Copy, Serialize)]
struct Said {
    title: &'static str,
    detail: &'static str,
}

/// What Quit asks while `working` Agents work, on a Mac (`mac`) or not:
/// a title and the line under it; nothing with none at work.
pub fn asks(working: usize, mac: bool) -> Option<(String, &'static str)> {
    let said = match working {
        0 => return None,
        1 => ONE,
        _ => MANY,
    };
    let here = if mac { MAC } else { ELSEWHERE };
    let title = (said.title)
        .replace("{n}", &working.to_string())
        .replace("{here}", here);
    Some((title, said.detail))
}

/// What Restart now asks while `working` Agents work: Quit's title, and
/// that the restart stops them; nothing with none at work.
pub fn restart_asks(working: usize, mac: bool) -> Option<(String, &'static str)> {
    let (title, _) = asks(working, mac)?;
    let detail = if working == 1 {
        RESTART_ONE
    } else {
        RESTART_MANY
    };
    Some((title, detail))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The words as the contract carries them, for TypeScript.
    #[derive(Serialize)]
    struct Words {
        one: Said,
        many: Said,
        quit: &'static str,
        cancel: &'static str,
        mac: &'static str,
        elsewhere: &'static str,
    }

    const WORDS: Words = Words {
        one: ONE,
        many: MANY,
        quit: QUIT,
        cancel: "Cancel",
        mac: MAC,
        elsewhere: ELSEWHERE,
    };

    #[test]
    fn quit_asks_in_one_set_of_words_how_many_agents_work_here() {
        assert_eq!(asks(0, true), None, "none at work: no question");
        assert_eq!(
            asks(1, true),
            Some((
                "An Agent works on this Mac".to_owned(),
                "Quitting Banda stops it too."
            ))
        );
        assert_eq!(
            asks(2, true),
            Some((
                "2 Agents work on this Mac".to_owned(),
                "Quitting Banda stops them too."
            ))
        );
        assert_eq!(
            asks(3, false),
            Some((
                "3 Agents work on this computer".to_owned(),
                "Quitting Banda stops them too."
            ))
        );
        assert_eq!(QUIT, "Quit anyway");
    }

    #[test]
    fn restart_now_asks_under_quits_title() {
        assert_eq!(restart_asks(0, false), None);
        assert_eq!(
            restart_asks(1, false),
            Some((
                "An Agent works on this computer".to_owned(),
                "Restarting Banda's engine stops it too."
            ))
        );
        assert_eq!(
            restart_asks(2, true),
            Some((
                "2 Agents work on this Mac".to_owned(),
                "Restarting Banda's engine stops them too."
            ))
        );
    }

    /// Writes the words beside the generated types, as ts-rs writes them,
    /// so the window, macOS's dialog and the menu bar read them from here.
    #[test]
    fn export_the_quit_words() {
        let Ok(dir) = std::env::var("TS_RS_EXPORT_DIR") else {
            return;
        };
        let file = std::path::Path::new(&dir).join("QUIT.ts");
        let words = serde_json::to_string_pretty(&WORDS).unwrap();
        let text = format!(
            "// Written by engine/src/quit.rs. Do not edit this file manually.\n\n\
             /** What Quit Banda asks while Agents work, the same everywhere (ADR\n \
             * 0086, decision 3): `{{n}}` is how many, `{{here}}` this machine. */\n\
             export const QUIT_WORDS = {words} as const\n"
        );
        if std::fs::read_to_string(&file).ok().as_deref() != Some(text.as_str()) {
            std::fs::create_dir_all(file.parent().unwrap()).unwrap();
            std::fs::write(&file, text).unwrap();
        }
    }
}
